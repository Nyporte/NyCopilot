import AppKit
import CryptoKit
import MacPlatform

/// macOS half of the Clipboard module: watch the pasteboard, hand each copy — text, or an image kept
/// as a PNG beside the database — to the core, and open the picker that pastes an earlier one back
/// where you were typing.
@MainActor
final class ClipboardShell: ModuleShell {
    let id = "clipboard"
    let title = L("Clipboard")
    let symbolName = "doc.on.clipboard"

    enum Action {
        static let open = "clipboard.open"
    }

    /// Markers apps put on copies that must not be kept: passwords, one-time codes, and other
    /// transient or generated content (see nspasteboard.org).
    nonisolated private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"
    ]

    /// Copied images, as `<uuid>.png` beside the database.
    static let images = ImageFolder("Clipboard")
    /// Bigger images (a raw photo) are left out of the history.
    private static let maximumImageBytes = 30 * 1024 * 1024

    private let services: CopilotServices
    private lazy var picker = ClipboardPicker(core: services.core, images: Self.images)
    private var watcher: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    private var cleanup: DispatchWorkItem?
    private var lockObservers: [NSObjectProtocol] = []

    init(services: CopilotServices) {
        self.services = services
        // Pruning and finding unused images read every entry: after launch, not during it.
        DispatchQueue.main.asyncAfter(deadline: .now() + 7) { [core = services.core] in
            core.clipboardPrune()
            Self.removeUnusedImages(core: core)
        }
        startWatching()
        // Nothing is copied behind a locked screen; don't wake twice a second for it.
        let center = DistributedNotificationCenter.default()
        lockObservers = [
            center.addObserver(forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.watcher?.invalidate(); self?.watcher = nil }
            },
            center.addObserver(forName: .init("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.startWatching() }
            }
        ]
        picker.onPick = { [weak self] entry, target in self?.paste(entry, into: target) }
        picker.onCopy = { [weak self] entry in self?.put(entry) }
        picker.onVerb = { [weak services] verb, entry, app in
            services?.act(verb, text: entry.text, image: entry.image.flatMap(Self.images.image), from: app)
        }
    }

    var hotKeyActions: [HotKeyCenter.Action] {
        [.init(id: Action.open, title: L("Open clipboard history"),
               defaultCombination: .init(keyCode: 9, modifiers: HotKeyCombination.option | HotKeyCombination.command),
               handler: { [weak self] in self?.open() })]
    }

    func menuItems() -> [NSMenuItem] {
        [services.menuItem(L("Clipboard History…"), symbol: "doc.on.clipboard", hotKey: Action.open, target: self, action: #selector(openFromMenu))]
    }

    func makeSettingsPane() -> SettingsPane? { ClipboardPane(services: services) }

    /// Off, copies are no longer kept; on, they are again.
    func setEnabled(_ on: Bool) { try? services.core.setSetting(.clipboardEnabled, on) }

    /// The pasteboard has no change notification; its counter is cheap to read.
    private func startWatching() {
        guard watcher == nil else { return }
        watcher = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.checkPasteboard() }
        }
        watcher?.tolerance = 0.2
    }

    func shutdown() {
        lockObservers.forEach(DistributedNotificationCenter.default().removeObserver)
        watcher?.invalidate()
        picker.close()
    }

    @objc private func openFromMenu() { open() }

    // MARK: Watching

    private func checkPasteboard() {
        let board = NSPasteboard.general
        guard board.changeCount != lastChange else { return }
        lastChange = board.changeCount
        guard !TemporaryPasteboard.ownChanges.contains(lastChange) else { return }
        guard Self.keeps(types: board.types ?? []) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        let source: [String: Any] = ["app": app?.localizedName ?? "", "bundle_id": app?.bundleIdentifier ?? ""]
        if let text = board.string(forType: .string) {
            add(source.merging(["text": text]) { _, new in new })
        } else if let data = board.data(forType: .png) ?? board.data(forType: .tiff), data.count <= Self.maximumImageBytes {
            Task { await addImage(data, source: source) }
        }
    }

    /// Whether a copy with these types belongs in the history: never one an app marks private,
    /// transient, or generated, and never copied files (their names come as text, their icons as images).
    nonisolated static func keeps(types: [NSPasteboard.PasteboardType]) -> Bool {
        !types.contains { privateTypes.contains($0.rawValue) || $0 == .fileURL }
    }

    /// Images are converted and written off the main thread; a screenshot can be tens of megabytes.
    private func addImage(_ data: Data, source: [String: Any]) async {
        let images = Self.images
        let kept = await Task.detached(priority: .utility) { () -> (name: String, digest: String, width: Int, height: Int)? in
            guard let bitmap = NSBitmapImageRep(data: data), bitmap.pixelsWide > 0, bitmap.pixelsHigh > 0,
                  let png = bitmap.representation(using: .png, properties: [:]), let name = images.keep(png: png) else { return nil }
            let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            return (name, digest, bitmap.pixelsWide, bitmap.pixelsHigh)
        }.value
        guard let kept else { return }
        let record = add(source.merging(["image": kept.name, "digest": kept.digest, "width": kept.width, "height": kept.height]) { _, new in new })
        // Not kept (off, an excluded app, already pinned), or it replaced an earlier copy of the same image.
        if record == nil { try? FileManager.default.removeItem(at: images.file(kept.name)) }
        scheduleImageCleanup()
    }

    /// The id of the record kept, or nil when the core left the copy out.
    @discardableResult
    private func add(_ params: [String: Any]) -> String? {
        do {
            return try services.core.clipboardAdd(params)
        } catch {
            Diagnostics.note("clipboard", "couldn’t keep a copy: \(error.localizedDescription)")
            return nil
        }
    }

    /// Images of pruned or replaced entries go once copying has paused a while, not after each copy:
    /// finding them means reading every entry.
    private func scheduleImageCleanup() {
        cleanup?.cancel()
        let work = DispatchWorkItem { [core = services.core] in MainActor.assumeIsolated { Self.removeUnusedImages(core: core) } }
        cleanup = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 60, execute: work)
    }

    /// Images no entry, kept or pinned, names any more go; those younger than `graceSeconds` stay.
    static func removeUnusedImages(core: NyCore, graceSeconds: TimeInterval = 60) {
        images.removeUnused(core: core, collections: [.clipboardItems, .clipboardPinned], graceSeconds: graceSeconds)
    }

    // MARK: Picking

    /// Captures where you're typing first, so the pick can be pasted back there.
    private func open() {
        if picker.isVisible { picker.close(); return }
        guard let app = NSWorkspace.shared.frontmostApplication,
              app.processIdentifier != ProcessInfo.processInfo.processIdentifier else { picker.present(target: nil, source: nil); return }
        Task {
            let target = try? await InputTarget.capture(pid: app.processIdentifier)
            picker.present(target: target, source: app)
        }
    }

    /// The pick becomes the clipboard, then is pasted into the field you came from. Without a field
    /// to paste into — or Accessibility — it stays on the clipboard for ⌘V.
    private func paste(_ entry: ClipboardEntry, into target: InputTarget?) {
        guard put(entry) else { return }
        guard let target else {
            services.toast.show(L("Copied"), detail: L("Press ⌘V to paste."), style: .success)
            return
        }
        Task {
            do {
                let close = { self.picker.close(returningFocus: false) }
                if let text = entry.text { try await target.insert(text, prepareForPaste: close) }
                else { try await target.pasteClipboard(prepareForPaste: close) }
                Diagnostics.note("clipboard", "pasted from history")
            } catch {
                Diagnostics.note("clipboard", "didn’t paste: \(error.localizedDescription)")
                services.toast.show(L("Copied"), detail: L("Press ⌘V to paste."), style: .success)
            }
            // Pasting puts the clipboard back as it was: the pick itself.
            lastChange = NSPasteboard.general.changeCount
        }
    }

    /// The entry on the clipboard, and back at the top of the history; false if its image is gone.
    @discardableResult
    private func put(_ entry: ClipboardEntry) -> Bool {
        let board = NSPasteboard.general
        if let text = entry.text {
            board.clearContents()
            board.setString(text, forType: .string)
            lastChange = board.changeCount
            add(["text": text, "app": entry.app ?? ""])
            return true
        }
        guard let name = entry.image, let png = try? Data(contentsOf: Self.images.file(name)) else {
            services.toast.show(L("That image is no longer kept"), style: .warning)
            return false
        }
        let item = NSPasteboardItem()
        item.setData(png, forType: .png)
        if let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation { item.setData(tiff, forType: .tiff) }
        board.clearContents()
        board.writeObjects([item])
        lastChange = board.changeCount
        add(["image": name, "digest": entry.digest ?? "", "width": entry.width ?? 0, "height": entry.height ?? 0, "app": entry.app ?? ""])
        return true
    }
}
